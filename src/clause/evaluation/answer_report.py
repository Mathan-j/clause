"""Render the answering evaluation into one artifact for humans and one for CI.

Pure rendering, the same discipline as `clause.evaluation.report`: this module
touches no database, no Qdrant, no model. Its only job is to turn dataclasses
some other layer (`clause.evaluation.answer_run`) already computed into
`reports/answers.md` and `reports/answers.json`.

Citation resolution is reported as an assertion, not a metric: `enforce`
guarantees every `Answer` it returns carries only resolved citations, so a
resolution rate below 1.0 can only mean the enforcement path itself broke
somewhere upstream of that guarantee -- not that some answers happened to be
weaker than others. It is rendered as a loud contract breach for exactly that
reason, distinct from every other figure in this report, which is a genuine
measurement with no single "correct" value.
"""

import json
from collections.abc import Sequence
from dataclasses import asdict, dataclass
from pathlib import Path
from typing import Any

from clause.evaluation.answer_metrics import SupportDistribution


@dataclass(frozen=True, slots=True)
class AnswerFingerprint:
    """What produced these numbers -- the answering-path analogue of Phase 2's
    `Fingerprint`. Not compared against a committed report by any CI gate
    (Task 11 keeps `make answer-eval` out of CI entirely); it exists so a
    reader of `reports/answers.md` can tell what model, threshold and inputs
    produced the figures next to it.
    """

    model_file: str
    model_sha256: str
    n_ctx: int
    threshold: float
    golden_sha256: str
    adversarial_sha256: str
    corpus_documents: int
    git_commit: str

    def to_dict(self) -> dict[str, Any]:
        return asdict(self)


@dataclass(frozen=True, slots=True)
class ThresholdRow:
    """One row of the refusal-threshold sweep.

    `false_refusals` counts golden questions refused at this threshold whose
    answer *was* retrievable (a real cost of raising the bar); `answered` and
    `refused` count the golden set, `adversarial_refused` and
    `adversarial_answered` count the out-of-corpus set at the same threshold.
    """

    threshold: float
    answered: int
    refused: int
    false_refusals: int
    adversarial_refused: int
    adversarial_answered: int


SUPPORT_SIGNAL_SENTENCE = (
    "This is a term-overlap proxy, not entailment -- it catches a sentence "
    "citing a passage it shares no vocabulary with, and misses a fluent "
    "paraphrase that reverses the meaning."
)

LIMITATIONS = (
    "The golden set (`data/golden/kyc-v1.jsonl`) is model-drafted, not "
    "human-verified -- every figure measured against it inherits that "
    "provenance, the same caveat Phase 2's `reports/eval.md` states.",
    "`effective_date` is absent for every document in this corpus (see "
    "`clause.answering.schema.Citation`'s docstring), so no citation can "
    "state when the rule it quotes actually took effect -- only when the "
    "circular carrying it was published.",
    f"{SUPPORT_SIGNAL_SENTENCE} It is reported as a distribution and is not "
    "a faithfulness score, specifically so it cannot be quoted as one.",
    "The adversarial set (`data/adversarial/out-of-corpus-v1.jsonl`) holds a "
    "small number of questions per kind; its refusal rate should be read "
    "with the error bars that size implies, not as a precise percentage.",
)


def build_answer_report(
    rows: Sequence[ThresholdRow],
    fingerprint: AnswerFingerprint,
    support: SupportDistribution,
    *,
    resolution_rate: float,
) -> dict[str, Any]:
    return {
        "fingerprint": fingerprint.to_dict(),
        "resolution_rate": resolution_rate,
        "support": asdict(support),
        "sweep": [asdict(r) for r in rows],
    }


def _render_header() -> list[str]:
    return [
        "# Answering evaluation",
        "",
        "Generated by `make answer-eval`. Every figure here is produced by "
        "that command from the committed golden and adversarial sets; "
        "nothing in this file is estimated.",
        "",
    ]


def _render_resolution(resolution_rate: float) -> list[str]:
    lines = ["## Citation resolution", ""]
    if resolution_rate < 1.0:
        lines.append(
            f"**The citation contract rejected "
            f"{1.0 - resolution_rate:.1%} of generated drafts.** "
            f"{resolution_rate:.4f} of drafts survived enforcement and were "
            "returned as answers; the rest cited something that did not "
            "resolve, or asserted a fact with no citation at all, and were "
            "discarded rather than returned. "
            "**This is the contract working, not failing.** A returned "
            "`Answer` carrying an unresolvable citation is impossible by "
            "construction -- `validate.enforce` raises before an `Answer` is "
            "built -- so this figure measures how often the model produced "
            "something the corpus would not support, and how often that was "
            "caught. It is a property of the generator, not of the "
            "enforcement path."
        )
    else:
        lines.append(
            "Every generated draft survived the citation contract: each one "
            "cited only spans that resolved against the corpus. Note this "
            "measures the *generator* -- a returned `Answer` with an "
            "unresolvable citation cannot exist, because `validate.enforce` "
            "raises before one is constructed."
        )
    lines.append("")
    return lines


def _render_sweep(rows: Sequence[dict[str, Any]]) -> list[str]:
    lines = [
        "## Threshold sweep",
        "",
        "Retrieval runs once per question; this sweep is arithmetic over the "
        "scores recorded from that single pass, not a re-retrieval per "
        "threshold. `false refusals` counts golden questions refused at that "
        "threshold whose answer was in fact retrievable at some rank.",
        "",
        "| threshold | answered | refused | false refusals | adversarial refused "
        "| adversarial answered |",
        "|---:|---:|---:|---:|---:|---:|",
    ]
    for r in rows:
        lines.append(
            f"| {r['threshold']:.2f} | {r['answered']} | {r['refused']} "
            f"| {r['false_refusals']} | {r['adversarial_refused']} "
            f"| {r['adversarial_answered']} |"
        )
    lines.append("")
    return lines


def _render_support(support: dict[str, Any]) -> list[str]:
    return [
        "## Support signal",
        "",
        SUPPORT_SIGNAL_SENTENCE,
        "",
        f"Computed over **{support['n']}** factual sentence(s) produced at "
        f"the default threshold: mean **{support['mean']:.3f}**, "
        f"**{support['at_or_above_half']}** at or above 0.5, "
        f"**{support['zero']}** at zero.",
        "",
    ]


def _render_limitations() -> list[str]:
    lines = ["## Limitations", ""]
    for item in LIMITATIONS:
        lines.append(f"- {item}")
    lines.append("")
    return lines


def _render_fingerprint(fp: dict[str, Any]) -> list[str]:
    return [
        "## Provenance fingerprint",
        "",
        "| field | value |",
        "|---|---|",
        f"| model file | `{fp['model_file']}` |",
        f"| model sha256 | `{fp['model_sha256'][:16]}...` |",
        f"| n_ctx | {fp['n_ctx']} |",
        f"| default threshold | {fp['threshold']} |",
        f"| golden set sha256 | `{fp['golden_sha256'][:16]}...` |",
        f"| adversarial set sha256 | `{fp['adversarial_sha256'][:16]}...` |",
        f"| corpus documents | {fp['corpus_documents']} |",
        f"| git commit at run time | `{fp['git_commit']}` |",
        "",
    ]


def render_answer_markdown(report: dict[str, Any]) -> str:
    lines = _render_header()
    lines += _render_resolution(report["resolution_rate"])
    lines += _render_sweep(report["sweep"])
    lines += _render_support(report["support"])
    lines += _render_limitations()
    lines += _render_fingerprint(report["fingerprint"])
    return "\n".join(lines)


def write_answer_report(report: dict[str, Any], md_path: Path, json_path: Path) -> None:
    md_path.parent.mkdir(parents=True, exist_ok=True)
    json_path.parent.mkdir(parents=True, exist_ok=True)
    md_path.write_text(render_answer_markdown(report), encoding="utf-8", newline="\n")
    json_path.write_text(
        json.dumps(report, indent=2, sort_keys=True) + "\n", encoding="utf-8", newline="\n"
    )
